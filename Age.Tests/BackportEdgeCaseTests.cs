using AgeSharp.Crypto;
using AgeSharp;
using Xunit;

namespace Age.Tests;

/// <summary>
/// Guards on the backported paths that the ordinary round-trip tests never reach: a custom
/// identity returning the wrong-sized file key, random access over a truncated payload, and the
/// encode overload's own bounds check.
/// </summary>
public class BackportEdgeCaseTests
{
    // An identity writes into a 16-byte buffer the library supplies, so it can no longer hand
    // back a key of the wrong size. What it can still do is fill the buffer only partly and claim
    // success: that key derives the wrong header key, and the MAC refuses it.
    private sealed class PartialKeyIdentity : IIdentity
    {
        public bool TryUnwrap(Stanza stanza, Span<byte> fileKey)
        {
            fileKey[..15].Fill(0xAB);
            return true;
        }
    }

    // age-plugin.md:227 requires the exact same label set across every stanza wrapping one file
    // key. Labels come out of the wrap, as in go-age, so each of these wraps first.
    private sealed class LabelledRecipient(string? label) : IRecipientWithLabels
    {
        public IReadOnlyList<Stanza> Wrap(ReadOnlySpan<byte> fileKey) => WrapWithLabels(fileKey).Stanzas;

        public LabelledStanzas WrapWithLabels(ReadOnlySpan<byte> fileKey) =>
            new([new Stanza("test", [], [])], label is null ? [] : [label]);
    }

    [Theory]
    [InlineData("postquantum", null)]
    [InlineData(null, "postquantum")]
    [InlineData("postquantum", "acme-internal")]
    public void MixingPostQuantumWithAnythingElse_NamesWhatIsLost(string? a, string? b)
    {
        var ex = Assert.Throws<AgeException>(() => Encrypt(a, b));

        Assert.Contains("post-quantum and classical", ex.Message, StringComparison.Ordinal);
        Assert.Contains("quantum computer", ex.Message, StringComparison.Ordinal);
    }

    [Theory]
    [InlineData("acme-internal", null, "\"acme-internal\"", "none")]
    [InlineData("acme-internal", "globex", "\"acme-internal\"", "\"globex\"")]
    public void MixingOtherLabels_NamesBothSides(string? a, string? b, string expectedA, string expectedB)
    {
        var ex = Assert.Throws<AgeException>(() => Encrypt(a, b));

        Assert.Contains(expectedA, ex.Message, StringComparison.Ordinal);
        Assert.Contains(expectedB, ex.Message, StringComparison.Ordinal);
        Assert.DoesNotContain("quantum", ex.Message, StringComparison.Ordinal);
    }

    private static void Encrypt(string? a, string? b)
    {
        using var input = new MemoryStream("x"u8.ToArray());
        using var output = new MemoryStream();

        new Recipients(new LabelledRecipient(a), new LabelledRecipient(b)).Encrypt(input, output);
    }

    [Fact]
    public void FileKey_ZeroesOnDispose()
    {
        var key = FileKey.Fresh();
        var live = key.Bytes.ToArray();

        Assert.Contains(live, b => b != 0);

        key.Dispose();

        Assert.Throws<ObjectDisposedException>(() => key.Bytes.ToArray());
        key.Dispose(); // idempotent
    }

    // AgeSharp's own identities recover the key into an array first and hand it over. A key of
    // the wrong size (a plugin's file-key reply, say) is refused, and refusing it must not mean
    // abandoning it: the array is zeroed either way (S9).
    [Theory]
    [InlineData(15, 16)]
    [InlineData(16, 15)]
    public void FileKey_DeliverZeroesWhatItRefuses(int recoveredSize, int bufferSize)
    {
        var recovered = Enumerable.Repeat((byte)0xAB, recoveredSize).ToArray();

        Assert.ThrowsAny<Exception>(() => FileKey.Deliver(recovered, new byte[bufferSize]));
        Assert.DoesNotContain(recovered, b => b != 0);
    }

    [Fact]
    public void FileKey_DeliverZeroesWhatItHandsOver()
    {
        var recovered = Enumerable.Range(1, 16).Select(i => (byte)i).ToArray();
        var buffer = new byte[16];

        Assert.True(FileKey.Deliver(recovered, buffer));
        Assert.Equal(Enumerable.Range(1, 16).Select(i => (byte)i), buffer);
        Assert.DoesNotContain(recovered, b => b != 0);
    }

    [Fact]
    public void AnIdentityThatFillsOnlyPartOfTheKey_FailsTheMac()
    {
        using var real = X25519Identity.Generate();

        using var input = new MemoryStream("edge"u8.ToArray());
        using var encrypted = new MemoryStream();
        new Recipients(real.Recipient).Encrypt(input, encrypted);

        using var source = new MemoryStream(encrypted.ToArray());
        using var output = new MemoryStream();

        Assert.Throws<AgeAuthenticationException>(
            () => new Identities(new PartialKeyIdentity()).Decrypt(source, output));
        Assert.Equal(0, output.Length);
    }

    // S9 — a recipient that throws mid-wrap is routine: a plugin binary missing, a user declining
    // a touch prompt. The file key is already generated by then, so every one of those paths has
    // to clear it. Captured here by handing the recipient the key it is asked to wrap and then
    // throwing, so the test can inspect what the library left behind.
    private sealed class ThrowingRecipient : IRecipient
    {
        public byte[]? SeenFileKey { get; private set; }

        public IReadOnlyList<Stanza> Wrap(ReadOnlySpan<byte> fileKey)
        {
            SeenFileKey = fileKey.ToArray();
            throw new AgePluginException("recipient declined");
        }
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void WhenARecipientThrows_TheFileKeyIsCleared(bool detached)
    {
        var recipient = new ThrowingRecipient();

        Assert.Throws<AgePluginException>(() =>
        {
            using var input = new MemoryStream("x"u8.ToArray());
            using var a = new MemoryStream();
            using var b = new MemoryStream();

            if (detached)
                new Recipients(recipient).EncryptDetached(input, a, b);
            else
                new Recipients(recipient).Encrypt(input, a);
        });

        // The recipient saw a real, non-zero key...
        Assert.NotNull(recipient.SeenFileKey);
        Assert.Contains(recipient.SeenFileKey!, b => b != 0);

        // ...and the library's own copy must not still be live. Verified by wrapping again and
        // confirming a fresh key each time, so a retained buffer would be visible as a repeat.
        var second = new ThrowingRecipient();

        Assert.Throws<AgePluginException>(() =>
        {
            using var input = new MemoryStream("x"u8.ToArray());
            using var a = new MemoryStream();
            new Recipients(second).Encrypt(input, a);
        });

        Assert.NotEqual(recipient.SeenFileKey, second.SeenFileKey);
    }

    // --- Random access over damaged payloads: the same rejections the forward-only path makes ---

    private static byte[] Encrypted(X25519Identity identity, int size)
    {
        var plaintext = new byte[size];
        for (var i = 0; i < size; i++) plaintext[i] = (byte)(i * 31 % 251);

        using var input = new MemoryStream(plaintext);
        using var output = new MemoryStream();
        new Recipients(identity.Recipient).Encrypt(input, output);

        return output.ToArray();
    }

    [Fact]
    public void RandomAccess_OverAPayloadWithNoChunks_IsRejected()
    {
        using var identity = X25519Identity.Generate();
        var file = Encrypted(identity, 32);

        // Keep the header and the 16-byte payload nonce, drop every chunk.
        var headerEnd = FindPayloadStart(file);
        var truncated = file[..(headerEnd + 16)];

        Assert.Throws<AgeAuthenticationException>(() =>
        {
            using var source = new MemoryStream(truncated);
            using var reader = new Identities(identity).DecryptReader(source);
        });
    }

    [Fact]
    public void RandomAccess_OverAChunkTooSmallForItsTag_IsRejected()
    {
        using var identity = X25519Identity.Generate();
        var file = Encrypted(identity, 32);

        // A payload of fewer than 16 bytes cannot even hold an authentication tag.
        var headerEnd = FindPayloadStart(file);
        var truncated = file[..(headerEnd + 16 + 8)];

        Assert.Throws<AgeAuthenticationException>(() =>
        {
            using var source = new MemoryStream(truncated);
            using var reader = new Identities(identity).DecryptReader(source);
        });
    }

    // The payload begins immediately after the header's MAC line.
    private static int FindPayloadStart(byte[] file)
    {
        var text = System.Text.Encoding.ASCII.GetString(file);
        var macLine = text.IndexOf("--- ", StringComparison.Ordinal);

        return text.IndexOf('\n', macLine) + 1;
    }

    // H6 — deriving the post-quantum recipient runs a full ML-KEM-768 key generation, and it was
    // re-run on every access, so decrypting an N-stanza header cost N keygens. Caching makes that
    // one. A bounded constant factor rather than a denial-of-service vector, but free to fix.
    [Fact]
    public void PostQuantumRecipient_IsDerivedOnceAndReused()
    {
        using var identity = MlKem768X25519Identity.Generate();

        var first = identity.Recipient;
        var second = identity.Recipient;

        Assert.Same(first, second);
        Assert.Equal(first.ToString(), second.ToString());
    }

    [Fact]
    public void PostQuantumRecipient_IsStillGuardedAfterDispose()
    {
        var identity = MlKem768X25519Identity.Generate();
        _ = identity.Recipient; // populate the cache first

        identity.Dispose();

        // The cache must not become a way to reach a disposed identity's derived key.
        Assert.Throws<ObjectDisposedException>(() => identity.Recipient);
    }

    // --- The span-filling encoder's own guard ---

    [Fact]
    public void EncodeIntoTooSmallABuffer_Throws()
    {
        var data = new byte[32];

        Assert.Throws<InvalidOperationException>(() => Base64Unpadded.Encode(data, new char[4]));
    }

    [Fact]
    public void EncodeIntoAnExactlySizedBuffer_Works()
    {
        var data = new byte[16];
        var destination = new char[Base64Unpadded.MaxEncodedLength(data.Length)];

        var written = Base64Unpadded.Encode(data, destination);

        Assert.Equal(Base64Unpadded.Encode(data), new string(destination, 0, written));
    }

    [Fact]
    public void EncodeOfNothingWritesNothing()
    {
        Assert.Equal(0, Base64Unpadded.Encode([], new char[4]));
    }
}
